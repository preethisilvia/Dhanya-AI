def get_nutrition(food_name):
    """
    Return nutrition information for a detected food.
    Handles small naming differences.
    """

    if not food_name:
        return None

    food_name_clean = food_name.strip()

    # Exact match
    if food_name_clean in NUTRITION_DATA:
        return NUTRITION_DATA[food_name_clean]

    # Case-insensitive match
    for key, value in NUTRITION_DATA.items():
        if key.lower() == food_name_clean.lower():
            return value

    # Common aliases
    aliases = {
        "chick peas": "Chick Peas",
        "chickpea": "Chick Peas",
        "chickpeas": "Chick Peas",
        "green gram": "green gram",
        "moong": "green gram",
        "finger millet": "Finger millet",
        "ragi": "Finger millet",
        "pearl millet": "pearl millet",
        "bajra": "pearl millet",
        "barnyard millet": "Barnyard millet",
        "kuthiraivali": "Barnyard millet",
        "rice": "Rice",
        "wheat": "Wheat",
        "oats": "Oats",
        "peas": "peas",
        "dry peas": "peas",
        "bamboo rice": "Bamboo rice"
    }

    alias_key = aliases.get(food_name_clean.lower())

    if alias_key:
        return NUTRITION_DATA.get(alias_key)

    return None


def nutrition_for_grams(food_name, grams):
    """
    Calculate nutrition for any serving size.

    Example:
        nutrition_for_grams("green gram", 50)
    """

    data = get_nutrition(food_name)

    if data is None:
        return None

    try:
        grams = float(grams)
    except (TypeError, ValueError):
        return None

    if grams <= 0:
        return None

    factor = grams / 100.0

    result = {
        "food": data["display_name"],
        "serving_g": grams,
        "energy_kcal": round(data["energy_kcal"] * factor, 1),
        "protein_g": round(data["protein_g"] * factor, 2),
        "carbohydrate_g": round(data["carbohydrate_g"] * factor, 2),
        "fat_g": round(data["fat_g"] * factor, 2),
        "fiber_g": round(data["fiber_g"] * factor, 2),
    }

    # Calculate available minerals when values exist
    for nutrient in [
        "calcium_mg",
        "iron_mg",
        "magnesium_mg",
        "phosphorus_mg",
        "potassium_mg"
    ]:
        value = data.get(nutrient)

        if value is None:
            result[nutrient] = None
        else:
            result[nutrient] = round(value * factor, 2)

    return result


